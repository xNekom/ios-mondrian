#!/usr/bin/env python3
"""Generate mondrian_cp_profile.h from a local PongAdrenoCpProfile.h.

The Pong profile is GPL-2.0-only (generated from the NothingOSS SM8475 gen7
sources).  It is a local build input, like the Qualcomm firmware: the generated
header carries only the register numbers and the CP tables and is not
committed.  The kernel includes it with __has_include and falls back to a
"profile not built in" path.

Usage:
    tools/gen-cp-profile.py /path/to/PongAdrenoCpProfile.h \
        /path/to/mondrian_cp_profile.h
"""

import argparse
import re
import sys


TABLES = {
    "PongCpHwcg": "mondrian_cp_hwcg",
    "PongCpGbif": "mondrian_cp_gbif",
    "PongCpProtect": "mondrian_cp_protect",
    "PongCpRestore": "mondrian_cp_restore",
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("profile")
    parser.add_argument("output")
    args = parser.parse_args()
    text = open(args.profile).read()

    out = [
        "/* generated by tools/gen-cp-profile.py; do not commit",
        " * source: PongAdrenoCpProfile.h (GPL-2.0-only, local build input) */",
        "#ifndef MONDRIAN_CP_PROFILE_H",
        "#define MONDRIAN_CP_PROFILE_H",
        "#include <stdint.h>",
    ]
    for line in text.splitlines():
        if re.match(r"^#define GEN7_[A-Za-z0-9_]+ ", line):
            out.append(line)
    for old, new in TABLES.items():
        match = re.search(
            r"static const uint32_t %s\[\](\[\d*\])?\s*=\s*\{(.*?)\n\};" % old,
            text, re.S)
        if not match:
            raise SystemExit("missing table %s" % old)
        out.append("static const uint32_t %s[]%s = {%s\n};" %
                   (new, match.group(1) or "", match.group(2)))
        out.append("#define %s_count (sizeof(%s) / sizeof(%s[0]))" % (new, new, new))
    out.append("#endif")
    with open(args.output, "w") as header:
        header.write("\n".join(out) + "\n")
    print("%s -> %s (%d defines)" %
          (args.profile, args.output, sum(1 for l in out if l.startswith("#define GEN7_"))))


if __name__ == "__main__":
    sys.exit(main())
