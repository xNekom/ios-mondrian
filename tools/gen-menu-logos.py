#!/usr/bin/env python3
"""Generate the boot-menu logo bitmaps (shim/menu_logos.h).

Two 1-bit silhouettes drawn with circles, capsules and cuts, then packed
MSB-first per row. The shim blits them with a scale factor; there are no
binary assets, so the images live in the tree as generated C arrays and a
comment in the header says they come from this script.

    python3 tools/gen-menu-logos.py   # -> shim/menu_logos.h
"""
import math
import os

W = 64


def blank(w, h):
    return [[0] * w for _ in range(h)]


def circle(b, cx, cy, r, v=1):
    h, w = len(b), len(b[0])
    r2 = r * r
    for y in range(len(b)):
        for x in range(w):
            if v == 0:
                if (x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= r2:
                    b[y][x] = 0
            elif (x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= r2:
                b[y][x] = 1


def capsule(b, p1, p2, r, v=1):
    h, w = len(b), len(b[0])
    (x1, y1), (x2, y2) = p1, p2
    dx, dy = x2 - x1, y2 - y1
    ll = dx * dx + dy * dy
    for y in range(h):
        for x in range(w):
            px, py = x + 0.5, y + 0.5
            t = 0.0
            if ll > 0:
                t = ((px - x1) * dx + (py - y1) * dy) / ll
                t = min(1.0, max(0.0, t))
            qx, qy = x1 + t * dx, y1 + t * dy
            d = (px - qx) ** 2 + (py - qy) ** 2
            if v == 0:
                if d <= r * r:
                    b[y][x] = 0
            elif d <= r * r:
                b[y][x] = 1


def ellipse_rot(b, cx, cy, rx, ry, angle, v=1):
    h, w = len(b), len(b[0])
    c, s = math.cos(angle), math.sin(angle)
    for y in range(h):
        for x in range(w):
            px, py = x + 0.5 - cx, y + 0.5 - cy
            # coordinates in the ellipse frame
            ux, uy = c * px + s * py, -s * px + c * py
            if v == 0:
                if (ux / rx) ** 2 + (uy / ry) ** 2 <= 1:
                    b[y][x] = 0
            elif (ux / rx) ** 2 + (uy / ry) ** 2 <= 1:
                b[y][x] = 1


def apple():
    """A fruit with a bite and a leaf: close enough to read as iOS."""
    b = blank(W, W)
    # the body: two shoulder lobes make the dip; the big circle rounds it
    circle(b, 19, 36, 14)
    circle(b, 45, 36, 14)
    circle(b, 32, 48, 16)
    circle(b, 32, 58, 8)
    # stem, short, just poking out of the dip
    capsule(b, (31.5, 22), (31.5, 33), 1.7)
    # leaf, tilted, small
    ellipse_rot(b, 44, 13, 7.0, 4.0, math.radians(-30))
    # the bite, right side: two arcs, modest
    circle(b, 54, 29, 10, 0)
    circle(b, 60, 40, 6.5, 0)
    return b, W, W


def android():
    """The classic robot head: dome, antennae, eyes."""
    b = blank(W, 40)
    # the dome, a circle whose lower half runs off the bitmap
    circle(b, 32, 40, 26)
    # the eyes, holes
    circle(b, 21, 21, 4.5, 0)
    circle(b, 43, 21, 4.5, 0)
    # the antennae
    capsule(b, (13, 4), (21, 13), 2.6)
    capsule(b, (51, 4), (43, 13), 2.6)
    return b, W, 40


def pack(name, b):
    h, w = len(b), len(b[0])
    rows = []
    for y in range(h):
        cells = b[y]
        pad = (8 - w % 8) % 8
        row = cells + [0] * pad
        by = []
        for i in range(0, w + pad, 8):
            byte = 0
            for bit in range(8):
                byte = (byte << 1) | row[i + bit]
            by.append(byte)
        rows.append(", ".join("0x%02x" % v for v in by))
    body = "\n".join("\t" + r + "," for r in rows)
    return ("static const unsigned char %s[%d * %d] = {\n%s\n};\n"
            "#define %s_W %d\n#define %s_H %d\n"
            % (name, w, h, body, name, w, name, h))


def main():
    a, aw, ah = apple()
    n, nw, nh = android()
    out = (
        "/*\n"
        " * The logos of the boot menu, generated by tools/gen-menu-logos.py:\n"
        " * one-bit-per-pixel silhouettes, packed MSB first per row, to be\n"
        " * blitted with a scale factor by shim/menu.c. Do not edit the bit\n"
        " * maps by hand; change the generator and run it.\n"
        " */\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        "/* The Apple fruit, white. */\n"
        + pack("m_apple", a) + "\n"
        "/* The Android robot head, green. */\n"
        + pack("m_android", n) + "\n"
    )
    path = os.path.join(os.path.dirname(__file__), "..", "shim", "menu_logos.h")
    with open(path, "w") as f:
        f.write(out)
    print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
