#!/usr/bin/env python3
"""Generate mondrian_glblob.h from the CoreAnimation dylibs and the UI hook.

Those dylibs live in the iOS root image, which means a 14 GB userdata flash per
change. The kernel can instead carry them and write them into /private/var/vm
while the root is being mounted (boot argument glblob=1), the same way it
carries the SQE firmware, so a userland change costs one kernel build and one
`fastboot boot` instead of a flash. The UI hook is optional: without it the
array is empty and the kernel keeps injecting the copy in /usr/libexec.

    tools/gen-glblob.py OUTDIR out/gpu/mondrian-gl.dylib out/gpu/mondrian-inject.dylib [UI-HOOK.dylib] [PROBE.dylib]

writes OUTDIR/mondrian_glblob.h. OUTDIR is the XNU source tree the kernel is
built from, i.e. bsd/dev in the build tree (the header is a generated local
input, never committed, like mondrian_sqe_fw.h).
"""

import argparse
import os


def array(name, data):
    if not data:
        # An empty initializer list is not C; a zero byte with a length of 0
        # says the same thing and the kernel skips the write.
        return [f"static const unsigned char {name}[] = {{ 0x00 }};",
                f"static const unsigned {name}_len = 0;"]
    lines = [f"static const unsigned char {name}[] = {{"]
    for start in range(0, len(data), 16):
        chunk = data[start:start + 16]
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    lines.append(f"static const unsigned {name}_len = {len(data)};")
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("outdir")
    parser.add_argument("gl")
    parser.add_argument("inject")
    parser.add_argument("ui_hook", nargs="?")
    parser.add_argument("probe", nargs="?")
    args = parser.parse_args()

    out = ["/* Generated by tools/gen-glblob.py; not committed. */",
           "#ifndef _MONDRIAN_GLBLOB_H_",
           "#define _MONDRIAN_GLBLOB_H_",
           ""]
    with open(args.gl, "rb") as handle:
        gl = handle.read()
    with open(args.inject, "rb") as handle:
        inject = handle.read()
    if args.ui_hook is None:
        hook = b""
    else:
        with open(args.ui_hook, "rb") as handle:
            hook = handle.read()
    if args.probe is None:
        probe = b""
    else:
        with open(args.probe, "rb") as handle:
            probe = handle.read()
    out += array("mondrian_gl_dylib", gl)
    out.append("")
    out += array("mondrian_inject_dylib", inject)
    out.append("")
    out += array("mondrian_ui_hook_dylib", hook)
    out.append("")
    out += array("mondrian_probe_dylib", probe)
    out += ["", "#endif", ""]
    path = os.path.join(args.outdir, "mondrian_glblob.h")
    with open(path, "w") as handle:
        handle.write("\n".join(out))
    print(f"{path}: gl {len(gl)} bytes, inject {len(inject)} bytes, "
          f"hook {len(hook)} bytes, probe {len(probe)} bytes")


if __name__ == "__main__":
    main()
