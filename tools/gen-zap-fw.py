#!/usr/bin/env python3
"""Generate mondrian_zap_fw.h from a730_zap.mdt, .b01 (code) and .b02 (signature).

The ZAP firmware is Qualcomm; it is a local build input and is not committed.
The split firmware has the ELF header plus the separate signature file in the
MDT and the relocatable code in .b01 (Pong's indices: code=1, signature=2).

Usage:
    tools/gen-zap-fw.py a730_zap.mdt a730_zap.b01 a730_zap.b02 \
        /path/to/mondrian_zap_fw.h
"""

import argparse
import sys


def emit(name, data):
    out = ["static const uint8_t %s[] = {" % name]
    for start in range(0, len(data), 16):
        out.append(",".join("0x%02x" % byte for byte in data[start:start + 16]) + ",")
    out.append("};")
    out.append("#define %s_len %uu" % (name, len(data)))
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("mdt")
    parser.add_argument("code")
    parser.add_argument("signature")
    parser.add_argument("output")
    args = parser.parse_args()
    mdt = open(args.mdt, "rb").read()
    code = open(args.code, "rb").read()
    sig = open(args.signature, "rb").read()
    out = [
        "/* generated by tools/gen-zap-fw.py; do not commit */",
        "#ifndef MONDRIAN_ZAP_FW_H",
        "#define MONDRIAN_ZAP_FW_H",
        "#include <stdint.h>",
    ]
    out += emit("mondrian_zap_mdt", mdt)
    out += emit("mondrian_zap_code", code)
    out += emit("mondrian_zap_sig", sig)
    out.append("#endif")
    with open(args.output, "w") as header:
        header.write("\n".join(out) + "\n")
    print("%s: mdt %d, code %d, sig %d -> %s" %
          (args.mdt, len(mdt), len(code), len(sig), args.output))


if __name__ == "__main__":
    sys.exit(main())
