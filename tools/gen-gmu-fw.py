#!/usr/bin/env python3
"""Generate mondrian_gmu_fw.h from a captured gmu_gen70000.bin.

The GMU firmware is a Qualcomm blob taken from the phone's vendor partition;
it is not committed.  This tool turns it into the C header that
bsd/dev/mondrian_gpu.c includes when present, so the kernel image carries the
firmware only in local test builds.

Usage:
    tools/gen-gmu-fw.py /path/to/gmu_gen70000.bin /path/to/mondrian_gmu_fw.h
"""

import argparse
import struct
import sys


def parse(data):
    blocks = []
    off = 0
    while off + 16 <= len(data):
        addr, length, typ, value = struct.unpack_from("<IIII", data, off)
        if length:
            if off + 16 + length > len(data):
                raise SystemExit("truncated block at 0x%x" % off)
            blocks.append((addr, length, data[off + 16:off + 16 + length]))
        off += 16 + length
    if off != len(data):
        raise SystemExit("trailing bytes at 0x%x" % off)
    return blocks


def emit(blocks):
    out = [
        "/* generated by tools/gen-gmu-fw.py; do not commit */",
        "#ifndef MONDRIAN_GMU_FW_H",
        "#define MONDRIAN_GMU_FW_H",
        "#include <stdint.h>",
        "struct mondrian_gmu_block { uint32_t addr; uint32_t len; const uint8_t *data; };",
    ]
    for index, (addr, length, payload) in enumerate(blocks):
        out.append("static const uint8_t mondrian_gmu_b%d[] = {" % index)
        for start in range(0, len(payload), 16):
            out.append(",".join("0x%02x" % byte for byte in payload[start:start + 16]) + ",")
        out.append("};")
    out.append("static const struct mondrian_gmu_block mondrian_gmu_blocks[] = {")
    for index, (addr, length, _) in enumerate(blocks):
        out.append("{0x%xu, 0x%xu, mondrian_gmu_b%d}," % (addr, length, index))
    out.append("};")
    out.append("#define mondrian_gmu_block_count "
               "(sizeof(mondrian_gmu_blocks)/sizeof(mondrian_gmu_blocks[0]))")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("firmware")
    parser.add_argument("output")
    args = parser.parse_args()
    data = open(args.firmware, "rb").read()
    blocks = parse(data)
    if not blocks:
        raise SystemExit("no data blocks")
    with open(args.output, "w") as out:
        out.write(emit(blocks))
    print("%s: %d blocks, %d bytes -> %s" %
          (args.firmware, len(blocks), sum(b[1] for b in blocks), args.output))


if __name__ == "__main__":
    main()
