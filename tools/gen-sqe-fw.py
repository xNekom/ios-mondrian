#!/usr/bin/env python3
"""Generate mondrian_sqe_fw.h from a captured a730_sqe.fw.

The SQE microcode is a Qualcomm blob from the phone's vendor partition; it is
not committed.  The file starts with a four-byte zero header and the CP fetches
the microcode from offset 4, so the generated array is the payload only.

Usage:
    tools/gen-sqe-fw.py /path/to/a730_sqe.fw /path/to/mondrian_sqe_fw.h
"""

import argparse
import sys


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("firmware")
    parser.add_argument("output")
    args = parser.parse_args()
    data = open(args.firmware, "rb").read()
    if len(data) < 8:
        raise SystemExit("truncated SQE firmware")
    if data[:4] != b"\0\0\0\0":
        raise SystemExit("unexpected SQE header %s" % data[:4].hex())
    payload = data[4:]
    out = [
        "/* generated by tools/gen-sqe-fw.py; do not commit */",
        "#ifndef MONDRIAN_SQE_FW_H",
        "#define MONDRIAN_SQE_FW_H",
        "#include <stdint.h>",
        "static const uint8_t mondrian_sqe_fw[] = {",
    ]
    for start in range(0, len(payload), 16):
        out.append(",".join("0x%02x" % byte for byte in payload[start:start + 16]) + ",")
    out.append("};")
    out.append("#define mondrian_sqe_fw_len ((uint32_t)sizeof(mondrian_sqe_fw))")
    out.append("#endif")
    with open(args.output, "w") as header:
        header.write("\n".join(out) + "\n")
    print("%s: %d payload bytes -> %s" % (args.firmware, len(payload), args.output))


if __name__ == "__main__":
    sys.exit(main())
